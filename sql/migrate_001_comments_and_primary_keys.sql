-- 将第一版空库迁移为统一自增主键、普通索引和中文注释。

ALTER TABLE stock_master
    DROP PRIMARY KEY,
    ADD COLUMN id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '自增主键' FIRST,
    ADD PRIMARY KEY (id),
    ADD KEY idx_stock_master_symbol (symbol),
    MODIFY COLUMN symbol VARCHAR(24) NOT NULL COMMENT '股票统一代码，如 600519.SH',
    MODIFY COLUMN stock_name VARCHAR(128) NULL COMMENT '股票名称',
    MODIFY COLUMN exchange VARCHAR(16) NULL COMMENT '交易所代码',
    MODIFY COLUMN board VARCHAR(32) NULL COMMENT '所属板块，如主板、科创板、创业板、北交所',
    MODIFY COLUMN industry_code VARCHAR(64) NULL COMMENT '行业代码',
    MODIFY COLUMN industry_name VARCHAR(128) NULL COMMENT '行业名称',
    MODIFY COLUMN is_st TINYINT(1) NOT NULL DEFAULT 0 COMMENT '是否为 ST 股票，0 否，1 是',
    MODIFY COLUMN price_limit_pct DECIMAL(10, 6) NULL COMMENT '当日涨跌停比例',
    MODIFY COLUMN list_date DATE NULL COMMENT '上市日期',
    MODIFY COLUMN delist_date DATE NULL COMMENT '退市日期',
    MODIFY COLUMN status VARCHAR(24) NOT NULL DEFAULT 'LISTED' COMMENT '股票状态',
    MODIFY COLUMN created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    MODIFY COLUMN updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    COMMENT='股票基础信息表';

ALTER TABLE stock_positions
