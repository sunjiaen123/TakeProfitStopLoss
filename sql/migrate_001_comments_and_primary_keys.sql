    MODIFY COLUMN updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    COMMENT='当前持仓表';

ALTER TABLE stock_daily_bars
    DROP PRIMARY KEY,
    ADD COLUMN id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '自增主键' FIRST,
    ADD PRIMARY KEY (id),
    ADD KEY idx_bars_symbol_date (symbol, trade_date),
    MODIFY COLUMN symbol VARCHAR(24) NOT NULL COMMENT '股票统一代码',
    MODIFY COLUMN trade_date DATE NOT NULL COMMENT '交易日期',
    MODIFY COLUMN open DECIMAL(20, 6) NOT NULL COMMENT '开盘价，原始可交易价格',
    MODIFY COLUMN high DECIMAL(20, 6) NOT NULL COMMENT '最高价，原始可交易价格',
    MODIFY COLUMN low DECIMAL(20, 6) NOT NULL COMMENT '最低价，原始可交易价格',
    MODIFY COLUMN close DECIMAL(20, 6) NOT NULL COMMENT '收盘价，原始可交易价格',
    MODIFY COLUMN pre_close DECIMAL(20, 6) NULL COMMENT '前一交易日收盘价',
    MODIFY COLUMN volume DECIMAL(24, 4) NULL COMMENT '成交量',
    MODIFY COLUMN amount DECIMAL(24, 4) NULL COMMENT '成交额',
    MODIFY COLUMN turnover_rate DECIMAL(14, 8) NULL COMMENT '换手率',
    MODIFY COLUMN adj_factor DECIMAL(24, 10) NOT NULL DEFAULT 1.0 COMMENT '复权因子',
    MODIFY COLUMN industry_code VARCHAR(64) NULL COMMENT '交易当日所属行业代码',
    MODIFY COLUMN is_suspended TINYINT(1) NOT NULL DEFAULT 0 COMMENT '是否停牌，0 否，1 是',
    MODIFY COLUMN source VARCHAR(32) NOT NULL DEFAULT 'UNKNOWN' COMMENT '行情数据来源',
    MODIFY COLUMN created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    MODIFY COLUMN updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    COMMENT='股票日线行情表';

